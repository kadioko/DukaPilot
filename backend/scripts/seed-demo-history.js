require("dotenv").config();

const prisma = require("../src/lib/prisma");
const { generateDemoSaleSchedule, MAX_SALES, MIN_SALES } = require("../src/lib/demoHistory");
const { normalizePhone } = require("../src/lib/phone");

const CONFIRMATION = "SEED_DUKAPILOT_DEMO_HISTORY";
const FEATURED_DEMO_PHONE = "+255700000002";

function todayInTanzania() {
  const parts = new Intl.DateTimeFormat("en-CA", {
    timeZone: "Africa/Dar_es_Salaam",
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  }).formatToParts(new Date());
  const values = Object.fromEntries(parts.map((part) => [part.type, part.value]));
  return `${values.year}-${values.month}-${values.day}`;
}

async function main() {
  if (process.env.DEMO_HISTORY_CONFIRM !== CONFIRMATION) {
    throw new Error(`Refusing to change sales. Set DEMO_HISTORY_CONFIRM=${CONFIRMATION} after reading docs/DEMO_HISTORY_SEEDING.md.`);
  }

  const phone = normalizePhone(process.env.DEMO_SHOP_PHONE || FEATURED_DEMO_PHONE);
  const user = await prisma.user.findUnique({ where: { phone }, include: { shop: true } });
  if (!user?.shop) throw new Error(`No merchant shop was found for ${phone}`);

  const knownFeaturedDemo = phone === FEATURED_DEMO_PHONE && user.shop.name === "Duka la Amina";
  if (!user.shop.isDemo && !knownFeaturedDemo) {
    throw new Error(`Refusing to seed ${user.shop.name}: mark the shop as a demo account before running this script.`);
  }

  const products = await prisma.product.findMany({
    where: { shopId: user.shop.id, isActive: true },
    select: { id: true, unit: true, buyingPrice: true, sellingPrice: true },
    orderBy: { id: "asc" },
  });

  const endDate = process.env.DEMO_HISTORY_END_DATE || todayInTanzania();
  const requestedCount = Number(process.env.DEMO_HISTORY_SALE_COUNT || 72);
  if (!Number.isInteger(requestedCount) || requestedCount < MIN_SALES || requestedCount > MAX_SALES) {
    throw new Error(`DEMO_HISTORY_SALE_COUNT must be a whole number from ${MIN_SALES} to ${MAX_SALES}`);
  }

  const preliminarySchedule = generateDemoSaleSchedule({ endDate, count: requestedCount, products });
  const firstDate = preliminarySchedule[0].createdAt.toISOString().slice(0, 10);
  const windowStart = new Date(`${firstDate}T00:00:00+03:00`);
  const recentCount = await prisma.sale.count({
    where: { shopId: user.shop.id, status: "COMPLETED", createdAt: { gte: windowStart } },
  });
  if (recentCount > MAX_SALES) {
    throw new Error(`This demo has ${recentCount} completed sales in the 30-day window. Refusing to leave a partial spike; reduce it to ${MAX_SALES} or fewer first.`);
  }

  const targetCount = Math.max(requestedCount, recentCount);
  const schedule = targetCount === requestedCount
    ? preliminarySchedule
    : generateDemoSaleSchedule({ endDate, count: targetCount, products });
  if (process.env.DEMO_HISTORY_DRY_RUN === "1") {
    console.log(`Dry run for ${user.shop.name} (${phone}).`);
    console.log(`Demo flag: ${user.shop.isDemo}; public catalog: ${user.shop.isCatalogPublished}; active products: ${products.length}.`);
    console.log(`Would redistribute ${recentCount} existing sales and create ${targetCount - recentCount} sales across 30 days ending ${endDate}.`);
    return;
  }

  const shop = await prisma.shop.update({
    where: { id: user.shop.id },
    data: { isDemo: true, isCatalogPublished: false },
  });
  const existingSales = await prisma.sale.findMany({
    where: { shopId: shop.id, status: "COMPLETED", createdAt: { gte: windowStart } },
    select: { id: true },
    orderBy: [{ receiptNumber: "asc" }, { id: "asc" }],
    take: targetCount,
  });

  for (let index = 0; index < existingSales.length; index += 1) {
    const createdAt = schedule[index].createdAt;
    await prisma.$transaction([
      prisma.sale.update({ where: { id: existingSales[index].id }, data: { createdAt } }),
      prisma.debt.updateMany({ where: { saleId: existingSales[index].id }, data: { createdAt } }),
    ]);
  }

  for (let index = existingSales.length; index < schedule.length; index += 1) {
    const sale = schedule[index];
    await prisma.$transaction(async (tx) => {
      const counter = await tx.shop.update({
        where: { id: shop.id },
        data: { nextSaleNumber: { increment: 1 } },
        select: { nextSaleNumber: true },
      });
      await tx.sale.create({
        data: {
          shopId: shop.id,
          totalAmount: sale.totalAmount,
          profit: sale.profit,
          paymentMethod: sale.paymentMethod,
          channel: sale.channel,
          pricingTier: sale.pricingTier,
          receiptNumber: counter.nextSaleNumber - 1,
          clientReference: `demo-history-v1:${sale.createdAt.toISOString()}:${index + 1}`,
          note: "Demo history generated by the guarded Prisma seeder",
          createdAt: sale.createdAt,
          items: { create: sale.items },
        },
      });
    });
  }

  const daily = new Map();
  for (const sale of schedule) {
    const key = new Intl.DateTimeFormat("en-CA", { timeZone: "Africa/Dar_es_Salaam" }).format(sale.createdAt);
    daily.set(key, (daily.get(key) || 0) + 1);
  }
  console.log(`Demo history ready for ${shop.name}: ${schedule.length} sales across ${daily.size} days.`);
  console.log(`Redistributed ${existingSales.length} existing sales and created ${schedule.length - existingSales.length} new demo-only sales.`);
  console.log("The shop is marked as demo and removed from the public catalog.");
}

main()
  .catch((error) => {
    console.error(error.message);
    process.exitCode = 1;
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
